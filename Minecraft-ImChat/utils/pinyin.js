/**
 * 获取字符串的首字母（大写）
 * @param {string} str 输入字符串
 * @returns {string} 首字母 A-Z 或 #
 */
export function getFirstLetter(str) {
  if (!str) return '#'
  const ch = str.charAt(0)
  const code = ch.charCodeAt(0)

  // 大写字母
  if (code >= 65 && code <= 90) return ch
  // 小写字母
  if (code >= 97 && code <= 122) return ch.toUpperCase()
  // 数字
  if (code >= 48 && code <= 57) return '#'
  // 非中文汉字范围
  if (code < 0x4E00 || code > 0x9FA5) return '#'

  for (const [letter, chars] of Object.entries(PINYIN_MAP)) {
    if (chars.includes(ch)) return letter
  }

  return '#'
}

/**
 * 获取字符串的拼音首字母用于排序分组
 * @param {string} str 输入字符串
 * @returns {string} 首字母
 */
export function getPinyinFirstLetter(str) {
  return getFirstLetter(str)
}

