export function getCountryById(id) {
  return countries.find(c => c.id === id)
}

export function getCountriesByContinent(continentId) {
  return countries.filter(c => c.continent === continentId)
}

export function findNearestCountry(lat, lng, maxDistance = 1500) {
  let nearest = null
  let minDist = Infinity
  for (const country of countries) {
    const d = haversineDistance(lat, lng, country.lat, country.lng)
    if (d < minDist && d < maxDistance) {
      minDist = d
      nearest = country
    }
  }
  return nearest
}

function haversineDistance(lat1, lng1, lat2, lng2) {
  const R = 6371
  const dLat = (lat2 - lat1) * Math.PI / 180
  const dLng = (lng2 - lng1) * Math.PI / 180
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
    Math.sin(dLng / 2) ** 2
  return 2 * R * Math.asin(Math.sqrt(a))
}
